#!/usr/bin/env node
/**
 * Re-copy Atlas's calendar kernel into the SDK and port its tests.
 *
 *   node codegen/atlas-calendar.mjs [--atlas <Atlas checkout>]
 *
 * 1. src/core/calendar.ts -> src/calendar/calendar.ts, byte for byte (Atlas owns it; never
 *    edit the copy).
 * 2. tests/unit/calendar.test.ts -> test/calendar-kernel.test.mjs: TypeScript's own
 *    transpiler strips the types, vitest becomes test/expect.mjs, the import points at dist.
 *
 * Then re-record the copy (Assembly's copy-drift: `python copy_drift.py record
 * src/calendar/SOURCES.json calendar.ts <Atlas>/src/core/calendar.ts`) and run npm test.
 * Atlas's src/core/calendar-lens.ts is adapted by hand in src/calendar/index.ts (it imports
 * Atlas's Element); compare it by eye when Atlas changes it.
 */
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const i = process.argv.indexOf('--atlas');
const ATLAS = i > 0 ? process.argv[i + 1] : 'C:/Users/Titus/Carrier/Forge/tools/atlas';

const commit = (rel) => execFileSync('git', ['-C', ATLAS, 'log', '-1', '--format=%h %ad', '--date=short', '--', rel], { encoding: 'utf8' }).trim();

copyFileSync(join(ATLAS, 'src/core/calendar.ts'), join(ROOT, 'src/calendar/calendar.ts'));
console.log(`copied src/core/calendar.ts (Atlas ${commit('src/core/calendar.ts')})`);

const src = readFileSync(join(ATLAS, 'tests/unit/calendar.test.ts'), 'utf8')
  .replace("from 'vitest'", "from './expect.mjs'")
  .replace("from '../../src/core/calendar'", "from '../dist/index.js'");
if (!src.includes("'./expect.mjs'") || !src.includes("'../dist/index.js'")) {
  console.error('the test file\'s imports moved: update this script'); process.exit(1);
}
const js = ts.transpileModule(src, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const head = `// GENERATED by codegen/atlas-calendar.mjs from Atlas's tests/unit/calendar.test.ts\n// (Atlas ${commit('tests/unit/calendar.test.ts')}). Do not edit: change Atlas's test, then re-run.\n`;
writeFileSync(join(ROOT, 'test/calendar-kernel.test.mjs'), head + js);
console.log('ported tests/unit/calendar.test.ts -> test/calendar-kernel.test.mjs');
