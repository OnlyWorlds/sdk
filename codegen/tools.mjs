// The tools list, baked into the package: src/tools.generated.ts (TOOLS) from the OnlyWorlds tools list
// (github.com/OnlyWorlds/tools, tools.json), vendored byte for byte at codegen/tools/tools.json and
// pinned in codegen/tools-pin.json (the commit and the file's sha256). A new listing reaches a surface
// at the package's next release, as the schema pin does.
//
//   node codegen/tools.mjs                  check the vendored file against the pin, write the module
//   node codegen/tools.mjs --check          exit 1 if the vendored file or the module is stale
//   node codegen/tools.mjs --repin COMMIT   vendor tools.json as GitHub serves it at COMMIT, pin it, write
//
// Only the keys openersFor reads are baked (id, name, url, client, rung, open); the rest of each row
// (the checks, the maker) stays in the list.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const VENDORED = join(ROOT, 'codegen', 'tools', 'tools.json');
const PIN = join(ROOT, 'codegen', 'tools-pin.json');
const OUT = join(ROOT, 'src', 'tools.generated.ts');
const REPO = 'https://github.com/OnlyWorlds/tools';
const KEYS = ['id', 'name', 'url', 'client', 'rung', 'open'];

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const die = (msg) => {
  console.error(`tools: ${msg}`);
  process.exit(1);
};

/** The module's text for the list's bytes, as the pin names them. */
function render(bytes, pin) {
  const doc = JSON.parse(bytes.toString('utf8'));
  if (doc.format !== 1) die(`tools.json format ${JSON.stringify(doc.format)}; this generator reads format 1`);
  if (!Array.isArray(doc.tools)) die('tools.json has no tools array');
  const rows = doc.tools.map((t) => {
    for (const k of KEYS) if (!(k in t)) die(`row ${JSON.stringify(t.id)} has no ${k}`);
    return Object.fromEntries(KEYS.map((k) => [k, t[k]]));
  });
  return [
    `// GENERATED by codegen/tools.mjs from the OnlyWorlds tools list. Do not hand-edit: the list is changed`,
    `// upstream, repinned (node codegen/tools.mjs --repin <commit>) and regenerated.`,
    `// Source: ${REPO} @ ${pin.commit}, tools.json sha256 ${pin.sha256}`,
    ``,
    `import type { OwTool } from './openers';`,
    ``,
    `/** The OnlyWorlds tools list's rows (format 1), in the list's order, as of this release: the keys openersFor reads. */`,
    `export const TOOLS: readonly OwTool[] = ${JSON.stringify(rows, null, 2)};`,
    ``,
  ].join('\n');
}

function readPinned() {
  const pin = JSON.parse(readFileSync(PIN, 'utf8'));
  const bytes = readFileSync(VENDORED);
  const got = sha256(bytes);
  if (got !== pin.sha256) die(`codegen/tools/tools.json is sha256 ${got}; the pin says ${pin.sha256}`);
  return { pin, bytes };
}

const args = process.argv.slice(2);
if (args[0] === '--repin') {
  const commit = args[1];
  if (!/^[0-9a-f]{40}$/.test(commit ?? '')) die('--repin takes the full 40-hex commit');
  const res = await fetch(`https://raw.githubusercontent.com/OnlyWorlds/tools/${commit}/tools.json`);
  if (!res.ok) die(`GitHub answered ${res.status} for tools.json at ${commit}`);
  const bytes = Buffer.from(await res.arrayBuffer());
  const pin = {
    _what: 'The recorded pin for the vendored OnlyWorlds tools list (codegen/tools/tools.json, byte for byte as GitHub serves it at the commit). Do not edit by hand: node codegen/tools.mjs --repin <commit>, and review the diff.',
    repo: REPO,
    commit,
    sha256: sha256(bytes),
    pinned_at: new Date().toISOString().slice(0, 10),
  };
  writeFileSync(VENDORED, bytes);
  writeFileSync(PIN, `${JSON.stringify(pin, null, 2)}\n`);
  writeFileSync(OUT, render(bytes, pin));
  console.log(`pinned ${commit}, sha256 ${pin.sha256}; wrote src/tools.generated.ts`);
} else if (args[0] === '--check') {
  const { pin, bytes } = readPinned();
  const want = render(bytes, pin);
  const have = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
  if (have !== want) die('src/tools.generated.ts is stale: run node codegen/tools.mjs');
  console.log(`ok: src/tools.generated.ts matches the tools list at ${pin.commit}`);
} else if (args.length === 0) {
  const { pin, bytes } = readPinned();
  writeFileSync(OUT, render(bytes, pin));
  console.log(`wrote src/tools.generated.ts from the tools list at ${pin.commit}`);
} else {
  die(`unknown arguments ${args.join(' ')}`);
}
