// The by-links-3d layout's directions table, baked into the package: src/layout-directions.generated.ts
// (LAYOUT_DIRECTIONS) from codegen/layout/directions.json, the table the method's shared fixture names by its sha256
// (codegen/schema-dist/profiles/layout-by-links-3d.fixture.json, its `table_sha256`, beside the same bytes as
// layout-by-links-3d.directions.json). For each count of parts k from 1 to 37, k unit vectors [x, y, z] spread over
// the sphere: the directions the method's groups are packed in. Computed once and kept
// as numbers, so no runtime's own cosine, sine or cube root is ever called for them and every runtime reads the same
// doubles. Each number is written in JavaScript's own shortest form, which reads back as the same double, and a
// negative zero as -0.
//
//   node codegen/layout_directions.mjs            write the module
//   node codegen/layout_directions.mjs --check    exit 1 if the module is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const SRC = new URL('./layout/directions.json', import.meta.url);
const OUT = new URL('../src/layout-directions.generated.ts', import.meta.url);
const K_MAX = 37;

function die(msg) {
  console.error(`layout_directions: ${msg}`);
  process.exit(1);
}

// a number as JavaScript writes it shortest (the same double reads back), a negative zero as -0
const num = (v) => (Object.is(v, -0) ? '-0' : String(v));

function render() {
  const bytes = readFileSync(SRC);
  const table = JSON.parse(bytes.toString('utf8'));
  if (table.k_max !== K_MAX) die(`directions.json: k_max is ${table.k_max}, not ${K_MAX}`);
  const dirs = table.directions;
  if (!dirs || typeof dirs !== 'object' || Object.keys(dirs).length !== K_MAX) die(`directions.json holds a count of parts outside 1 to ${K_MAX}`);
  const lines = [];
  for (let k = 1; k <= K_MAX; k++) {
    const row = dirs[String(k)];
    if (!Array.isArray(row) || row.length !== k) die(`directions.json: k = ${k} does not hold ${k} directions`);
    for (const p of row) {
      if (!Array.isArray(p) || p.length !== 3 || !p.every(Number.isFinite)) die(`directions.json: k = ${k} holds a direction that is not [x, y, z]`);
      if (!p.every((v) => Object.is(Number(num(v)), v))) die(`directions.json: k = ${k} holds a number that does not read back`);
    }
    const end = k === K_MAX ? '' : ',';
    lines.push(`  "${k}": [${row.map((p) => `[${p.map(num).join(', ')}]`).join(', ')}]${end}`);
  }
  return [
    '// GENERATED by codegen/layout_directions.mjs from codegen/layout/directions.json -- do not hand-edit.',
    '// Regenerate: node codegen/layout_directions.mjs',
    `// directions.json sha256 ${createHash('sha256').update(bytes).digest('hex')}`,
    '',
    '/**',
    ' * The by-links-3d layout\'s directions: for each count of parts k from 1 to 37 (the key, as a string), k unit',
    ' * vectors [x, y, z] spread over the sphere. Numbers, never computed at run time: every runtime reads the same',
    ' * doubles. The literal between `=` and `;` is JSON. Module-internal.',
    ' */',
    'export const LAYOUT_DIRECTIONS: { readonly [k: string]: ReadonlyArray<readonly number[]> } = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

const args = process.argv.slice(2);
if (args[0] === '--check') {
  const have = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
  if (have !== render()) die('src/layout-directions.generated.ts is stale: run node codegen/layout_directions.mjs');
  console.log('ok: src/layout-directions.generated.ts matches codegen/layout/directions.json');
} else if (args.length === 0) {
  writeFileSync(OUT, render());
  console.log('wrote src/layout-directions.generated.ts from codegen/layout/directions.json');
} else {
  die(`unknown arguments ${args.join(' ')}`);
}
