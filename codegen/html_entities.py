"""The HTML character references, as Python's html.unescape reads them, for src/convert/html.ts.

    python codegen/html_entities.py            write src/convert/html-entities.generated.ts
    python codegen/html_entities.py --check    exit 1 when the committed file is not what this writes

The import doors in src/convert/ read the HTML an export carries the way the Python package's doors
do, so that both give the same folder byte for byte. Python's html.parser unescapes text with
html.unescape: the HTML5 named references (html.entities.html5, with and without the semicolon),
and for a numeric reference the replacements and the code points it drops (html._invalid_charrefs,
html._invalid_codepoints). These tables are read here from the running Python, never typed: they
are the HTML standard's, unchanged in every Python the package is tested on (3.12 to 3.14).
Standard library only; the output is ASCII.
"""

from __future__ import annotations

import html
import html.entities
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "convert" / "html-entities.generated.ts"


def ranges(points: list[int]) -> str:
    out: list[str] = []
    i = 0
    while i < len(points):
        j = i
        while j + 1 < len(points) and points[j + 1] == points[j] + 1:
            j += 1
        out.append(f"{points[i]:x}" if i == j else f"{points[i]:x}-{points[j]:x}")
        i = j + 1
    return ",".join(out)


def render() -> str:
    names = html.entities.html5
    charrefs = html._invalid_charrefs  # type: ignore[attr-defined]
    codepoints = sorted(html._invalid_codepoints)  # type: ignore[attr-defined]
    lines = [
        "// GENERATED by codegen/html_entities.py from Python's html module: do not edit.",
        "// The HTML5 named character references (with and without the semicolon), and for a numeric",
        "// reference the replacements and the dropped code points, as html.unescape reads them.",
        "",
        f"/** {len(names)} names, each to its text. */",
        "export const HTML5_ENTITIES: Readonly<Record<string, string>> = "
        + json.dumps(dict(sorted(names.items())), ensure_ascii=True, separators=(",", ":"))
        + ";",
        "",
        "/** A numeric reference to one of these code points is read as the text beside it. */",
        "export const INVALID_CHARREFS: Readonly<Record<number, string>> = {"
        + ",".join(f"{k}:{json.dumps(v, ensure_ascii=True)}" for k, v in sorted(charrefs.items()))
        + "};",
        "",
        "/** A numeric reference to a code point in these hex ranges is dropped. */",
        f"export const INVALID_CODEPOINTS = '{ranges(codepoints)}';",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        # A Windows checkout may hold the file with CRLF line ends; the committed bytes are LF.
        have = OUT.read_bytes().replace(b"\r\n", b"\n") if OUT.exists() else b""
        if have != text.encode("ascii"):
            print(f"{OUT.name} is not what codegen/html_entities.py writes: run it and commit the result")
            return 1
        print(f"{OUT.name} is current")
        return 0
    OUT.write_bytes(text.encode("ascii"))
    print(f"wrote {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
