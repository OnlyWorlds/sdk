// The OW-18 NFC tables (Folder Format §4.7, serial 57; 2026-10-24): Unicode's own files at the pinned version,
// UnicodeData and CompositionExclusions, as three strings, `NFC_CLASS_RUNS`, `NFC_DECOMP` and `NFC_EXCLUDED`, which
// src/nfc.ts builds its NFC from. Never a runtime's NFC: Node 22's is Unicode 16.0's, which composes 20 code points
// 15.1 leaves alone.
//
//   node codegen/nfc_tables.mjs [<dir holding UnicodeData-15.1.0.txt and CompositionExclusions-15.1.0.txt>] > src/nfc-tables.generated.ts
//
// Prints the module, three strings in base 36:
//   NFC_CLASS_RUNS  `start.count.class`: `count` code points from `start` with that nonzero combining class (empty
//                   count is 1). Every other code point is class 0.
//   NFC_DECOMP      `gap.first[.second]`: each canonical decomposition mapping of UnicodeData (field 5 without a
//                   `<tag>`), in code point order, `gap` from the previous entry (the first from 0). Hangul syllables
//                   are not listed in the file and decompose by arithmetic.
//   NFC_EXCLUDED    the code points CompositionExclusions lists uncommented (script-specific and post composition
//                   version); singletons and non-starter decompositions are derived from NFC_DECOMP and the classes.
// The test in test/world-file.test.mjs reads the same two files and checks the built NFC for every code point, so a
// hand edit or a stale string fails there.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2] || fileURLToPath(new URL('./schema-dist/fixtures/owworld/', import.meta.url));
const b36 = (n) => n.toString(36);

const classes = [];
const decomps = [];
for (const line of readFileSync(join(dir, 'UnicodeData-15.1.0.txt'), 'utf8').split(/\r?\n/)) {
  if (!line) continue;
  const f = line.split(';');
  const cp = parseInt(f[0], 16);
  const ccc = Number(f[3]);
  if (ccc) classes.push([cp, ccc]);
  if (f[5] && !f[5].startsWith('<')) decomps.push([cp, f[5].split(' ').map(h => parseInt(h, 16))]);
}

const runs = [];
for (let i = 0; i < classes.length;) {
  const [s, c] = classes[i];
  let n = 1;
  while (i + n < classes.length && classes[i + n][0] === s + n && classes[i + n][1] === c) n++;
  runs.push([b36(s), n === 1 ? '' : b36(n), b36(c)].join('.'));
  i += n;
}

let prev = 0;
const entries = decomps.map(([cp, to]) => {
  if (to.length < 1 || to.length > 2) throw new Error(`U+${cp.toString(16)}: a canonical mapping of ${to.length}`);
  const e = [b36(cp - prev), ...to.map(b36)].join('.');
  prev = cp;
  return e;
});

const excluded = [];
for (const line of readFileSync(join(dir, 'CompositionExclusions-15.1.0.txt'), 'utf8').split(/\r?\n/)) {
  const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*#/.exec(line);
  if (!m) continue;
  const a = parseInt(m[1], 16);
  const z = m[2] ? parseInt(m[2], 16) : a;
  for (let c = a; c <= z; c++) excluded.push(b36(c));
}

// One constant as `'…' +` lines of at most 110 characters, broken after a comma.
const constant = (name, items, doc) => {
  const lines = [];
  let cur = '';
  items.forEach((it, i) => {
    const piece = it + (i < items.length - 1 ? ',' : '');
    if (cur && cur.length + piece.length > 110) { lines.push(cur); cur = ''; }
    cur += piece;
  });
  lines.push(cur);
  return `/** ${doc} */\nexport const ${name} =\n${lines.map(l => `  '${l}'`).join(' +\n')};\n`;
};

const out = [
  '// GENERATED by codegen/nfc_tables.mjs from the schema dist\'s fixtures/owworld/UnicodeData-15.1.0.txt and',
  '// CompositionExclusions-15.1.0.txt -- do not hand-edit. Regenerate: node codegen/nfc_tables.mjs > src/nfc-tables.generated.ts',
  '// OW-18\'s NFC (Folder Format §4.7, serial 57): the pinned Unicode version\'s own files, never a runtime\'s.',
  '',
  constant('NFC_CLASS_RUNS', runs, 'Nonzero canonical combining classes: `start.count.class` in base 36, an empty count is 1.'),
  constant('NFC_DECOMP', entries, 'Canonical decomposition mappings: `gap.first[.second]` in base 36, code point order, gap from the previous entry.'),
  constant('NFC_EXCLUDED', excluded, 'CompositionExclusions\' listed code points (base 36); singletons and non-starter decompositions are derived.'),
].join('\n');
process.stdout.write(out);
