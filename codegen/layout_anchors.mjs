// The by-kind layout's anchor table, baked into the package: src/layout-anchors.generated.ts (LAYOUT_ANCHORS) from
// codegen/layout/anchors.json, the table both packages and the shared fixture (test/fixtures/layout/by-kind.json,
// its `anchors`) hold byte for byte. For each count of kinds k from 1 to 22, the k points where the kinds sit on a
// circle: x = cos(-pi/2 + 2 pi i / k), y = sin(...), computed once and kept as numbers, so no runtime's own cos or
// sin is ever called and the picture is the same in every browser and language.
//
//   node codegen/layout_anchors.mjs            write the module
//   node codegen/layout_anchors.mjs --check    exit 1 if the module is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const SRC = new URL('./layout/anchors.json', import.meta.url);
const OUT = new URL('../src/layout-anchors.generated.ts', import.meta.url);

function die(msg) {
  console.error(`layout_anchors: ${msg}`);
  process.exit(1);
}

function render() {
  const bytes = readFileSync(SRC);
  const table = JSON.parse(bytes.toString('utf8'));
  const flat = [];
  for (let k = 1; k <= 22; k++) {
    const row = table[String(k)];
    if (!Array.isArray(row) || row.length !== k) die(`anchors.json: k = ${k} does not hold ${k} points`);
    for (const p of row) {
      if (!Array.isArray(p) || p.length !== 2 || !p.every(Number.isFinite)) die(`anchors.json: k = ${k} holds a point that is not [x, y]`);
      flat.push(p[0], p[1]);
    }
  }
  if (Object.keys(table).length !== 22) die('anchors.json holds a count of kinds outside 1 to 22');
  const lines = [];
  for (let i = 0; i < flat.length; i += 4) lines.push(`  ${flat.slice(i, i + 4).map(String).join(', ')},`);
  return [
    '// GENERATED by codegen/layout_anchors.mjs from codegen/layout/anchors.json -- do not hand-edit.',
    '// Regenerate: node codegen/layout_anchors.mjs',
    `// anchors.json sha256 ${createHash('sha256').update(bytes).digest('hex')}`,
    '',
    '/**',
    ' * The by-kind layout\'s anchors: for each count of kinds k from 1 to 22, the k points (x, y) on the unit circle',
    ' * where the kinds sit, flat, k = 1 first. The points of k start at index k * (k - 1) (two numbers per point).',
    ' * Numbers, never computed at run time: the picture is the same in every runtime. Module-internal.',
    ' */',
    'export const LAYOUT_ANCHORS: readonly number[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

const args = process.argv.slice(2);
if (args[0] === '--check') {
  const have = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
  if (have !== render()) die('src/layout-anchors.generated.ts is stale: run node codegen/layout_anchors.mjs');
  console.log('ok: src/layout-anchors.generated.ts matches codegen/layout/anchors.json');
} else if (args.length === 0) {
  writeFileSync(OUT, render());
  console.log('wrote src/layout-anchors.generated.ts from codegen/layout/anchors.json');
} else {
  die(`unknown arguments ${args.join(' ')}`);
}
